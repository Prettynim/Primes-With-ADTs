    /**~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
     *<pre>
     * Method       primesWithStack()
     * Description  A method to push user specified number of primes onto a 
     *              stack. A second stack is created to reverse the order in
     *              order to display the primes in increasing order. It is this
     *              second stack that is returned.
     * @return      copyStack--GenericStack
     * @author      <i>Young Min Kim</i>
     * Date         9/28/2026
     * History Log  7/18/2018, 4/5/2021, 10/1/2026    
    *</pre>
    *~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~*/
    public GenericStack primesWithStack()
    {
        outputJTextArea.setText("");
        int count = 0; outputBuffer = new StringBuilder();
        GenericStack<Integer> stack = new GenericStack<>();
        //needed only if want to write/read stack object to file
        GenericStack<Integer> copyStack = new GenericStack<>();
        // Repeatedly find prime numbers and push them onto the stack
        for (int number = 2; count < numberOfPrimes; number++)
        {
            if (isPrime(number))
            {
                stack.push(number);
                count++;            //increase the prime number count
            }
        }
        outputBuffer.append("The first " + numberOfPrimes +
            " prime numbers using stack in reverse order are: \n\n");
        count  = 1;     //for display
        while (!stack.isEmpty())
        {
            Integer obj = stack.pop();
            copyStack.push(obj);            //copy elements from stack
            outputBuffer.append(obj + "\t");

            if (count % NUMBER_PER_LINE == 0)
                outputBuffer.append("\n"); // advance to the new line
            count++;
        }
        outputJTextArea.setText(outputBuffer.toString());
        outputJTextArea.setCaretPosition(0);
        return copyStack;
    }
    
    /**~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
     *<pre>
     * Method       primesWithQueue()
     * Description  A method to add user specified number of primes onto a 
     *              queue. The queue is displayed by removing the elements in
     *              a queue FIFO fashion.
     * @author      <i>Young Min Kim</i>
     * Date         9/28/2026
     * History Log  7/18/2018, 4/5/2021, 10/1/2026    
    *</pre>
    *~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~*/
    public void primesWithQueue()
    {
        outputJTextArea.setText("");
        int count = 0; outputBuffer = new StringBuilder();
        GenericQueue<Integer> queue = new GenericQueue<>();
        // Repeatedly find prime numbers and enque them onto the queue
        for (int number = 2; count < numberOfPrimes; number++)
        {
            if (isPrime(number))
            {
                queue.enqueue(number);
                count++; // Increase the prime number count
            }
        }
        outputBuffer.append("The first " + numberOfPrimes +
            " prime numbers using queue are: \n\n");
        count = 1;  //for display formatting
        while (!queue.isEmpty())
        {
            outputBuffer.append(queue.dequeue() + "\t");

            if (count % NUMBER_PER_LINE == 0)
                outputBuffer.append("\n"); // advance to the new line
            count++;
        }
        outputJTextArea.setText(outputBuffer.toString());
        outputJTextArea.setCaretPosition(0);
    }
    
    /**~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
     *<pre>
     * Method       primesWithHashSet()
     * Description  A method to add user specified number of primes onto a 
     *              HashSet. The elemenents in the hashSet are diplayed 
     *              with two different loops: for loop and using an Iterator
     *              while loop. It is important to realize that the primes in
     *              the hashSet are not ordered.
     * @author      <i>Young Min Kim</i>
     * Date         9/28/2026
     * History Log  7/18/2018, 4/5/2021, 10/1/2026    
    *</pre>
    *~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~*/
    public void primesWithHashSet()
    {
        outputJTextArea.setText("");
        int count = 0; outputBuffer = new StringBuilder();
        Set<Integer> hashSet = new HashSet<>();
        // Repeatedly find prime numbers and enque them onto the queue
        for (int number = 2; count < numberOfPrimes; number++)
        {
            if (isPrime(number))
            {
                hashSet.add(number);
                count++; // Increase the prime number count
            }
        }
        outputBuffer.append("The first " + numberOfPrimes +
            " prime numbers using HashSet with for loop are (note lack of ordering): \n\n");
        count = 1;
        for(Object number : hashSet)
        {
            outputBuffer.append(number + "\t");
            if (count % NUMBER_PER_LINE == 0)
                outputBuffer.append("\n"); // advance to the new line
            count++;
        }
        count = 1;
        outputBuffer.append("\n\nThe first " + numberOfPrimes +
            " prime numbers using HashSet with iterator are (note lack of ordering): \n\n");
        Iterator iter = hashSet.iterator();
        while (iter.hasNext())
        {
            outputBuffer.append(iter.next() + "\t");
            if (count % NUMBER_PER_LINE == 0)
                outputBuffer.append("\n"); // advance to the new line
            count++;
        }
        outputJTextArea.setText(outputBuffer.toString());
        outputJTextArea.setCaretPosition(0);
    }
    
